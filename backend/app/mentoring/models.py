"""Ride journal (per case), shift-level mentoring summaries, personal notes, progress corrections
and manager-granted mentor access extensions.

Two separately editable parts share one ride id: the trainee's case description (rides) and the
mentor's per-case assessment (ride_assessments). Each part has its own version so concurrent edits
of different parts never overwrite each other."""
import uuid
from datetime import date, datetime

from sqlalchemy import Boolean, CheckConstraint, Date, ForeignKey, Integer, String, Text, UniqueConstraint, Uuid
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.core.db import Base
from app.core.types import tstz, uuid_pk

# Assessed actions and the four valid answers. A key that is absent (or null) means
# "not selected yet"; "not_performed" (חסר) is a valid, completed answer.
MARKER_KEYS = ("blood_pressure", "pulse", "breathing", "forms")
MARKER_VALUES = ("success", "failure", "not_performed", "partial")


class Ride(Base):
    __tablename__ = "rides"
    __table_args__ = (
        UniqueConstraint("trainee_id", "seq"),
        # Cancellation is all-or-nothing: who, when and why are recorded together.
        CheckConstraint("(cancelled_at IS NULL) = (cancelled_by_id IS NULL) "
                        "AND (cancelled_at IS NULL) = (cancel_reason IS NULL)", name="cancel_complete"),
        CheckConstraint("duplicate_of_id IS NULL OR (cancelled_at IS NOT NULL AND duplicate_of_id <> id)",
                        name="duplicate_of_cancelled"),
    )

    # Generated by the client so an offline draft keeps one identity across retries.
    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True)
    trainee_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id"), index=True)
    shift_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("shifts.id"), index=True)
    occurred_on: Mapped[date] = mapped_column(Date)
    seq: Mapped[int] = mapped_column(Integer)  # allocated on first server save; display order, not chronology
    description: Mapped[str | None] = mapped_column(String(200))  # trainee part: short case description
    description_version: Mapped[int] = mapped_column(Integer, default=0)
    description_updated_at: Mapped[datetime | None] = tstz(nullable=True)
    created_by_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id"))
    created_at: Mapped[datetime] = tstz()
    # Audited cancellation (e.g. a duplicate created on two devices). The row is kept; a cancelled
    # ride no longer counts toward progress, completeness or reminders, and cannot be edited.
    cancelled_at: Mapped[datetime | None] = tstz(nullable=True)
    cancelled_by_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id"))
    cancel_reason: Mapped[str | None] = mapped_column(String(300))
    duplicate_of_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("rides.id"))


class RideAssessment(Base):
    """Mentor part, created on first mentor save. markers: {key: value} for MARKER_KEYS."""

    __tablename__ = "ride_assessments"

    ride_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("rides.id"), primary_key=True)
    markers: Mapped[dict] = mapped_column(JSONB, default=dict)
    summary: Mapped[str | None] = mapped_column(Text)  # per-case mentor summary
    version: Mapped[int] = mapped_column(Integer, default=0)
    updated_at: Mapped[datetime] = tstz()
    updated_by_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id"))


class RideContributor(Base):
    """Who actually created/edited ride content (two mentors sharing a phone appear as the
    logged-in editor; crew membership is derived from the published schedule)."""

    __tablename__ = "ride_contributors"

    ride_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("rides.id"), primary_key=True)
    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id"), primary_key=True)
    first_at: Mapped[datetime] = tstz()
    last_at: Mapped[datetime] = tstz()


class MentoringSummary(Base):
    """Once per trainee per shift: strengths and areas for improvement. Each is either text or an
    explicit "no comments". Separate from per-case assessments and from personal notes."""

    __tablename__ = "mentoring_summaries"
    __table_args__ = (
        UniqueConstraint("trainee_id", "shift_id"),
        CheckConstraint("NOT (strengths_none AND strengths IS NOT NULL)", name="strengths_exclusive"),
        CheckConstraint("NOT (improvements_none AND improvements IS NOT NULL)", name="improvements_exclusive"),
    )

    id: Mapped[uuid.UUID] = uuid_pk()
    trainee_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id"), index=True)
    shift_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("shifts.id"))
    strengths: Mapped[str | None] = mapped_column(Text)
    strengths_none: Mapped[bool] = mapped_column(Boolean, default=False)
    improvements: Mapped[str | None] = mapped_column(Text)
    improvements_none: Mapped[bool] = mapped_column(Boolean, default=False)
    version: Mapped[int] = mapped_column(Integer, default=0)
    updated_at: Mapped[datetime] = tstz()
    updated_by_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id"))


class PersonalNote(Base):
    """Trainee's personal note. Unshared: author + admins only. Shared: also the author's current
    home-day manager, until unshared."""

    __tablename__ = "personal_notes"

    id: Mapped[uuid.UUID] = uuid_pk()
    author_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id"), index=True)
    shift_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("shifts.id"))
    content: Mapped[str] = mapped_column(Text)
    shared: Mapped[bool] = mapped_column(Boolean, default=False)
    version: Mapped[int] = mapped_column(Integer, default=1)
    created_at: Mapped[datetime] = tstz()
    updated_at: Mapped[datetime] = tstz()


class ProgressCorrection(Base):
    """Audited manager/admin correction layered over the derived ride count / last ride date."""

    __tablename__ = "progress_corrections"
    __table_args__ = (CheckConstraint("count_delta <> 0 OR last_ride_date IS NOT NULL", name="has_effect"),)

    id: Mapped[uuid.UUID] = uuid_pk()
    trainee_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id"), index=True)
    count_delta: Mapped[int] = mapped_column(Integer, default=0)
    last_ride_date: Mapped[date | None] = mapped_column(Date)
    reason: Mapped[str] = mapped_column(String(300))
    created_by_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id"))
    created_at: Mapped[datetime] = tstz()


class MentorAccessExtension(Base):
    __tablename__ = "mentor_access_extensions"

    id: Mapped[uuid.UUID] = uuid_pk()
    mentor_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id"), index=True)
    trainee_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id"), index=True)
    shift_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("shifts.id"))
    granted_by_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id"))
    starts_at: Mapped[datetime] = tstz()
    ends_at: Mapped[datetime] = tstz()
    revoked_at: Mapped[datetime | None] = tstz(nullable=True)
    revoked_by_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id"))

